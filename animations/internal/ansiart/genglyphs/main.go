// Command genglyphs generates complete block tables from pinned Unicode 16 data.
package main

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"strconv"
	"strings"
)

func main() {
	var data []byte
	var err error
	if len(os.Args) > 1 {
		data, err = os.ReadFile(os.Args[1])
	} else {
		var resp *http.Response
		resp, err = http.Get("https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt")
		if err == nil {
			defer resp.Body.Close()
			if resp.StatusCode != http.StatusOK {
				panic(resp.Status)
			}
			data, err = io.ReadAll(io.LimitReader(resp.Body, 4<<20))
		}
	}
	if err != nil {
		panic(err)
	}
	if fmt.Sprintf("%x", sha256.Sum256(data)) != "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f" {
		panic("UnicodeData 16.0 checksum mismatch")
	}
	names := map[rune]string{}
	var sext [64]rune
	var oct [256]rune
	for _, line := range strings.Split(string(data), "\n") {
		f := strings.Split(line, ";")
		if len(f) < 2 {
			continue
		}
		v, _ := strconv.ParseInt(f[0], 16, 32)
		r := rune(v)
		names[r] = f[1]
		for _, p := range []struct {
			prefix string
			table  []rune
		}{{"BLOCK SEXTANT-", sext[:]}, {"BLOCK OCTANT-", oct[:]}} {
			if strings.HasPrefix(f[1], p.prefix) {
				mask := 0
				for _, d := range strings.TrimPrefix(f[1], p.prefix) {
					mask |= 1 << (d - '1')
				}
				p.table[mask] = r
			}
		}
	}
	sext[0], sext[21], sext[42], sext[63] = ' ', '▌', '▐', '█'
	quad := [16]rune{' ', '▘', '▝', '▀', '▖', '▌', '▞', '▛', '▗', '▚', '▐', '▜', '▄', '▙', '▟', '█'}
	for m, r := range quad {
		expanded := (m & 3) | ((m & 3) << 2) | ((m & 12) << 2) | ((m & 12) << 4)
		oct[expanded] = r
	}
	for mask, r := range map[int]rune{1: 0x1cea8, 2: 0x1ceab, 3: 0x1fb82, 0x14: 0x1fbe6, 0x28: 0x1fbe7, 0x3f: 0x1fb85, 0x40: 0x1cea3, 0x80: 0x1cea0, 0xc0: 0x2582, 0xfc: 0x2586} {
		oct[mask] = r
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate from UnicodeData 16.0.0; DO NOT EDIT.\npackage ansiart")
	for _, p := range []struct {
		name  string
		table []rune
	}{{"QuadRunes", quad[:]}, {"sextantRunes", sext[:]}, {"octantRunes", oct[:]}} {
		fmt.Fprintf(&out, "\nvar %s = [%d]rune{\n", p.name, len(p.table))
		for mask, r := range p.table {
			if r == 0 || names[r] == "" {
				panic(fmt.Sprintf("missing %s mask %d", p.name, mask))
			}
			fmt.Fprintf(&out, "0x%X, // %02X: %s\n", r, mask, names[r])
		}
		fmt.Fprintln(&out, "}")
	}
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("glyphs_gen.go", formatted, 0644); err != nil {
		panic(err)
	}
}
